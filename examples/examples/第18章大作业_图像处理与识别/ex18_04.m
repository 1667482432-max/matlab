% ex18_04.m  |  例18.4 · 8×8 分块 DCT＋量化＋Zig-Zag（编码器核心）  |  AI 生成，已校验，R2023b
% 读取 MATLAB 自带的灰度演示图像（cameraman.tif）
I = imread('cameraman.tif');
% 如果不是灰度图像则转换为灰度
if size(I, 3) == 3
    I = rgb2gray(I);
end
% 转换为双精度并整体减去 128
I = double(I) - 128;
[M, N] = size(I);
% 若尺寸不是 8 的倍数，则在右侧和下侧补零
if mod(M, 8) ~= 0 || mod(N, 8) ~= 0
    Mpad = ceil(M/8)*8;
    Npad = ceil(N/8)*8;
    I = padarray(I, [Mpad-M, Npad-N], 0, 'post');
    M = Mpad;
    N = Npad;
end

% JPEG 标准亮度量化表
QTAB = [16 11 10 16 24 40 51 61
        12 12 14 19 26 58 60 55
        14 13 16 24 40 57 69 56
        14 17 22 29 51 87 80 62
        18 22 37 56 68 109 103 77
        24 35 55 64 81 104 113 92
        49 64 78 87 103 121 120 101
        72 92 95 98 112 100 103 99];

% 初始化整幅量化系数矩阵
Coeff = zeros(M, N);

% 按 8x8 分块进行二维 DCT 并量化
for r = 1:8:M
    for c = 1:8:N
        block = I(r:r+7, c:c+7);
        dct_block = dct2(block);                % 二维 DCT
        quant_block = round(dct_block ./ QTAB); % 逐元素相除并四舍五入
        Coeff(r:r+7, c:c+7) = quant_block;
    end
end

% 取第一个 8x8 量化块
Cq = Coeff(1:8, 1:8);

% 生成 Zig‑Zag 扫描顺序的线性索引（列优先）
% 行坐标序列（1‑based）
r = [1,1,2,3,2,1,1,2,3,4,5,4,3,2,1,1,2,3,4,5,6,7,6,5,4,3,2,1,1,2,3,4,5,6,7,8,8,7,6,5,4,3,2,2,3,4,5,6,7,8,8,7,6,5,4,3,4,5,6,7,8,8,7,6]';
% 列坐标序列（1‑based）
c = [1,2,1,1,2,3,4,3,2,1,1,2,3,4,5,6,5,4,3,2,1,1,2,3,4,5,6,7,8,7,6,5,4,3,2,1,1,2,3,4,5,6,7,8,8,7,6,5,4,3,2,3,4,5,6,7,8,8,7,6,5,4,5,6]';
idx = (c-1)*8 + r;   % 转换为线性索引

% 之字形扫描结果（1x64 行向量）
zz = Cq(idx)';
zz = zz(:)';

% 显示之字形向量
disp('之字形扫描结果 zz:');
disp(zz);
